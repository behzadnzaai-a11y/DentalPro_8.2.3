-- ============================================================================
-- طبق درخواست: کنار «کد ملی» یک فیلد «صادره از» اضافه شود که به‌صورت خودکار و
-- غیرقابل‌ویرایش از روی خودِ کد ملی پر می‌شود (مثل «خراسان جنوبی - بیرجند»).
--
-- مقدار از سه رقم اولِ کد ملی استخراج می‌شود؛ این سه رقم کدِ ادارهٔ ثبت احوالِ
-- صادرکننده است. نگاشت کامل (۵۹۱ کد) در سمت اپ داخل
-- app/src/main/java/com/example/util/NationalIdCityLookup.kt نگهداری می‌شود.
--
-- چرا ستون جدا و نه محاسبهٔ لحظه‌ای؟ چون جدول تقسیمات کشوری در طول زمان تغییر
-- می‌کند و مقدارِ ثبت‌شده در زمانِ پذیرش باید ثابت بماند؛ ضمناً گزارش‌ها و
-- جست‌وجوهای سمت سرور هم بدون تکرار منطق به آن دسترسی دارند.
--
-- بدون این ستون، سینک ابری مقدار issuancePlace را دور می‌ریخت (PostgREST ستون
-- ناشناخته را رد می‌کند) و «صادره از» بین دستگاه‌ها گم می‌شد.
-- ============================================================================

alter table public.patients
    add column if not exists issuance_place text not null default '';

comment on column public.patients.issuance_place is
    'محل صدور شناسنامه به شکل «استان - شهر»، مشتق‌شده از سه رقم اول کد ملی';
