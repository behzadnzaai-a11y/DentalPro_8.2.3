-- ============================================================================
-- DentalPro — Migration 0008: انتساب مراحل درمان به جلسه (stage_sessions)
-- ============================================================================
-- طبق درخواست: «با حذف جلسه وضعیت و مراحل تراپی‌ها همه جا آپدیت بشه».
--
-- تا پیش از این هیچ ردی از اینکه «کدام مرحله در کدام جلسه انجام شد» نگهداری
-- نمی‌شد؛ بنابراین با حذف یک جلسه معلوم نبود کدام مرحله باید برگردد و مراحلِ
-- انجام‌شده برای همیشه انجام‌شده می‌ماندند.
--
-- قالب مقدار: رکوردهای «appointmentId::stageName» که با «|||» از هم جدا شده‌اند.
-- مثال:  |||12::جلسه ۱: بی‌حسی…|||15::جلسه ۲: اُبچوریشن…
--
-- بدون این ستون، سینک ابری مقدار stageSessions را دور می‌ریخت (PostgREST ستون
-- ناشناخته را رد می‌کند) و انتساب‌ها بین دستگاه‌ها گم می‌شدند.
-- ============================================================================

alter table public.treatments
    add column if not exists stage_sessions text not null default '';

comment on column public.treatments.stage_sessions is
    'نگاشت مرحله به جلسه: رکوردهای appointmentId::stageName جداشده با |||';
