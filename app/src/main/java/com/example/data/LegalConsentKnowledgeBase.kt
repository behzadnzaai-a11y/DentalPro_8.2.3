    fun getTemplateById(id: String): LegalConsentTemplate {
        return getTemplates().firstOrNull { it.id == id } ?: getTemplates().last()
    }

    /**
     * تولید کد شناسه و هش دیجیتال یکتای سند حقوقی (کد تاییدیه قانونی ثبت الکترونیک)
     */
    fun generateLegalVerificationCode(patientCodeOrId: String, timestamp: Long): String {
        val hash = (patientCodeOrId.hashCode() xor timestamp.hashCode()).toString().replace("-", "").take(6)
        val datePart = java.text.SimpleDateFormat("yyMMdd-HHmm", java.util.Locale.US).format(java.util.Date(timestamp))
        return "IR-LEG-$datePart-$hash"
    }

    /**
     * تولید متن نهایی حقوقی با جایگذاری اطلاعات واقعی بیمار، پزشک و کلینیک
     */
    fun buildFinalLegalText(
        template: LegalConsentTemplate,
        patientName: String,
        patientNationalId: String,
        patientFatherName: String,
        signerRole: String, // "خود بیمار" یا "ولی قانونی / سرپرست"
        doctorName: String,
        medicalNo: String,
        clinicName: String,
        treatmentTitle: String
    ): String {
        val doctorStr = if (doctorName.isNotBlank()) doctorName else "پزشک معالج"
        val medicalStr = if (medicalNo.isNotBlank()) medicalNo else "ثبت‌شده در پرونده"
        val clinicStr = if (clinicName.isNotBlank()) clinicName else "کلینیک دندان‌پزشکی"
        val pNatId = if (patientNationalId.isNotBlank()) patientNationalId else "ثبت‌شده در پرونده"
        val fatherStr = if (patientFatherName.isNotBlank()) "فرزند: $patientFatherName | " else ""

        val rawText = template.defaultText
        return rawText
            .replace("{DOCTOR_NAME}", doctorStr)
            .replace("{MEDICAL_NO}", medicalStr)
            .replace("{CLINIC_NAME}", clinicStr)
            .replace("{PATIENT_NAME}", patientName)
            .replace("{PATIENT_NATIONAL_ID}", pNatId)
            .let { text ->
                if (treatmentTitle.isNotBlank() && !text.contains(treatmentTitle)) {
                    "عنوان اقدام درمانی/موضوع رضایت‌نامه: $treatmentTitle\n" +
                    "مشخصات امضاکننده: $patientName | کد ملی: $pNatId | $fatherStr سمت: $signerRole\n" +
                    "پزشک معالج: $doctorStr (نظام پزشکی: $medicalStr) | مرکز درمانی: $clinicStr\n\n" + text
                } else text
            }
    }
