package com.example.data

/**
 * فهرست استاندارد عناوین خدمات لابراتواری — به‌درخواست کاربر:
 * نام خدمت در تعرفهٔ لابراتوار «قابل تایپ» نیست و فقط از منوی کشویی انتخاب می‌شود؛
 * گزینه‌ها = این فهرست استاندارد + عناوین تراپی‌های تعریف‌شده در بخش تراپی‌ها
 * (TreatmentTemplate) تا نام‌گذاری در کل اپ یکپارچه بماند.
 */
object LabServiceCatalog {

    /** عناوین استاندارد خدمات لابراتوار دندان‌سازی (فارسی). */
    val standardTitles: List<String> = listOf(
        "روکش PFM (پرسلن روی فلز)",
        "روکش فول زیرکونیا",
        "روکش زیرکونیا پرسلن",
        "روکش ایمکس (E-max)",
        "روکش تمام‌فلزی",
        "روکش موقت (تمپ)",
        "لمینت سرامیکی (ونیر)",
        "کامپوزیت ونیر غیرمستقیم",
        "اینله / آنله سرامیکی",
        "پست و کور ریختگی",
        "فریم فلزی (امتحان فریم)",
        "بریج PFM",
        "بریج زیرکونیا",
        "کراون روی ایمپلنت",
        "اباتمنت کاستومایز ایمپلنت",
        "سورجیکال گاید ایمپلنت",
        "دست دندان کامل (فول دنچر)",
        "پروتز پارسیل آکریلی",
        "پروتز پارسیل کروم کبالت",
        "پروتز فلکسیبل",
        "ریلاین / ریبیس پروتز",
        "تعمیر پروتز / اضافه‌کردن دندان",
        "نایت‌گارد / اسپلینت اکلوزال",
        "تری بلیچینگ",
        "ریتینر ثابت / متحرک ارتودنسی",
        "پلاک متحرک ارتودنسی",
        "مدل مطالعه / کست تشخیصی"
    )

    /**
     * همهٔ گزینه‌های منوی «نام خدمت»: فهرست استاندارد + عناوین تراپی‌ها +
     * نام‌های قبلاً ثبت‌شده (تا رکوردهای قدیمی همچنان قابل انتخاب/ویرایش باشند).
     */
    fun options(
        therapyTitles: List<String>,
        existingServiceNames: List<String> = emptyList()
    ): List<String> =
        (standardTitles + therapyTitles + existingServiceNames)
            .map { it.trim() }
            .filter { it.isNotBlank() }
            .distinct()
}
