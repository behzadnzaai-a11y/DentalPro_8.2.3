    fun normalizeDigits(input: String): String {
        var output = input
        val persianDigits = charArrayOf('۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹')
        val arabicDigits = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')
        for (i in 0..9) {
            output = output.replace(persianDigits[i], (i + '0'.toInt()).toChar())
            output = output.replace(arabicDigits[i], (i + '0'.toInt()).toChar())
        }
        return output
    }

    fun parseShamsiDateString(str: String): Triple<Int, Int, Int?>? {
        if (str.isBlank()) return null
        val normalized = normalizeDigits(str)
        val parts = normalized.split("/")
        if (parts.size == 2) {
            val day = parts[0].trim().toIntOrNull() ?: return null
            val month = parts[1].trim().toIntOrNull() ?: return null
            return Triple(day, month, null)
        } else if (parts.size == 3) {
            val p0 = parts[0].trim().toIntOrNull() ?: return null
            val p1 = parts[1].trim().toIntOrNull() ?: return null
            val p2 = parts[2].trim().toIntOrNull() ?: return null
            return if (p0 > 1000) {
                Triple(p2, p1, p0) // Day, Month, Year
            } else if (p2 > 1000) {
                Triple(p0, p1, p2) // Day, Month, Year
            } else {
                Triple(p0, p1, null)
            }
        }
        return null
    }

    private fun parseDayMonth(str: String): Pair<Int, Int>? {
        if (str.isBlank()) return null
        val normalized = normalizeDigits(str)
        val parts = normalized.split("/")
        if (parts.size < 2) return null
        val day = parts[0].trim().toIntOrNull() ?: return null
        val month = parts[1].trim().toIntOrNull() ?: return null
        return Pair(day, month)
    }

    fun parseCsvToCalendarEvents(csvContent: String): List<AppCalendarEvent> {
        val events = mutableListOf<AppCalendarEvent>()
        val lines = csvContent.lines()
        if (lines.isEmpty()) return events

        val dataLines = if (lines.firstOrNull()?.contains("دسته‌بندی") == true || lines.firstOrNull()?.contains("دسته") == true) {
            lines.drop(1)
        } else {
            lines
        }

        for (line in dataLines) {
            if (line.isBlank()) continue

            val tokens = mutableListOf<String>()
            var inQuotes = false
            val sb = StringBuilder()
            for (ch in line) {
                if (ch == '\"') {
                    inQuotes = !inQuotes
                } else if (ch == ',' && !inQuotes) {
                    tokens.add(sb.toString().trim())
                    sb.setLength(0)
                } else {
                    sb.append(ch)
                }
            }
            tokens.add(sb.toString().trim())

            if (tokens.size < 5) continue

            val category = tokens.getOrNull(0) ?: ""
            val shamsiStr = tokens.getOrNull(1) ?: ""
            val qamariStr = tokens.getOrNull(2) ?: ""
            val miladiStr = tokens.getOrNull(3) ?: ""
            val title = tokens.getOrNull(4) ?: ""
            val isHolidayStr = tokens.getOrNull(5) ?: ""
            val description = tokens.getOrNull(6) ?: ""
            val personalType = tokens.getOrNull(7) ?: ""

            if (title.isBlank()) continue

            val shamsiDate = parseShamsiDateString(shamsiStr)
            val qamariDate = parseDayMonth(qamariStr)
            val miladiDate = parseDayMonth(miladiStr)

            val isHoliday = isHolidayStr == "بله" || isHolidayStr.contains("yes", ignoreCase = true)

            // نکته‌ی حیاتی: syncId باید برای رویدادهای مرجع/پیش‌فرض «قطعی» (deterministic) باشد،
            // نه UUID تصادفی. AppCalendarEvent به‌طور پیش‌فرض syncId را با UUID.randomUUID() پر
            // می‌کند؛ یعنی هر بار seedDefaultCalendarEvents دوباره اجرا شود (نصب مجدد، دستگاه
            // دوم، پاک کردن کامل داده، یا اجرای مجدد گیت نسخه‌ی calendar_events_1405_pdf_v3 روی
            // یک Room DB تازه)، همین ۱۹۰ رویداد با syncId های کاملاً جدید دوباره ساخته و از طریق
            // SyncEngine به‌عنوان رکوردهای «جدید» به سرور push می‌شوند — نتیجه‌اش رویدادهای
            // تکراری روی سرور است (هر بار seeding یک نسخه‌ی جدید). با ساختن یک syncId قطعی از
            // روی محتوای پایدار رویداد (دسته + تاریخ‌ها + عنوان)، هر بار seeding همان syncId قبلی
            // را تولید می‌کند و SyncEngine آن را UPSERT روی همان رکورد قبلی انجام می‌دهد، نه
            // ساختن رکورد تازه.
            val deterministicSyncId = "seed-" + java.util.UUID.nameUUIDFromBytes(
                listOf(
                    category,
                    shamsiDate?.first?.toString() ?: "",
                    shamsiDate?.second?.toString() ?: "",
                    shamsiDate?.third?.toString() ?: "",
                    qamariDate?.first?.toString() ?: "",
                    qamariDate?.second?.toString() ?: "",
                    miladiDate?.first?.toString() ?: "",
                    miladiDate?.second?.toString() ?: "",
                    title
                ).joinToString("|").toByteArray(Charsets.UTF_8)
            ).toString()

            events.add(AppCalendarEvent(
                category = category,
                shamsiDay = shamsiDate?.first,
                shamsiMonth = shamsiDate?.second,
                shamsiYear = shamsiDate?.third,
                qamariDay = qamariDate?.first,
                qamariMonth = qamariDate?.second,
                miladiDay = miladiDate?.first,
                miladiMonth = miladiDate?.second,
                title = title,
                isHolidayInIran = isHoliday,
                description = description,
                personalType = personalType,
                syncId = deterministicSyncId
            ))
        }
        return events
    }

