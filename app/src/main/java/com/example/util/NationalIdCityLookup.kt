    /**
     * «استان - شهرِ» صادرکنندهٔ شناسنامه را از روی کد ملی برمی‌گرداند،
     * یا null اگر کد ناقص باشد یا پیشوندش در جدول نباشد.
     */
    fun cityOf(nationalId: String): String? {
        val code = NationalIdValidator.padded(nationalId)
        if (code.length != 10) return null
        return CITY_BY_CODE[code.substring(0, 3)]
    }

    /**
     * مثل [cityOf] اما فقط وقتی جواب می‌دهد که کد ملی از نظر رقم کنترل هم
     * معتبر باشد — برای پر کردن خودکار فیلد «صادره از» همین را به کار می‌بریم
     * تا با کدهای نصفه‌کاره چیزی نمایش داده نشود.
     */
    fun cityOfValid(nationalId: String): String? =
        if (NationalIdValidator.isValid(nationalId)) cityOf(nationalId) else null

    /** تعداد کدهای پوشش‌داده‌شده — برای تست و بازبینی. */
    val size: Int get() = CITY_BY_CODE.size
